class PromptComposeError(ValueError):
    """IR / policy / render refused."""


@dataclass
class RenderResult:
    prompt: str
    domain: str
    ir: dict[str, Any]
    dropped_tags: tuple[str, ...] = ()
    rewrites: tuple[dict[str, str], ...] = ()
    recoverability: list[dict[str, Any]] = field(default_factory=list)

    def to_json(self) -> dict[str, Any]:
        return {
            "prompt": self.prompt,
            "prompt_domain": self.domain,
            "ir": self.ir,
            "dropped_tags": list(self.dropped_tags),
            "rewrites": list(self.rewrites),
            "recoverability": self.recoverability,
        }


_FILE_JSON_LOCK = threading.Lock()
_FILE_JSON_CACHE: dict[str, tuple[tuple[int, int], Any]] = {}


def _cached_json(path: Path) -> Any:
    sig = (path.stat().st_mtime_ns, path.stat().st_size)
    key = str(path)
    with _FILE_JSON_LOCK:
        hit = _FILE_JSON_CACHE.get(key)
        if hit and hit[0] == sig:
            return hit[1]
    payload = json.loads(path.read_text(encoding="utf-8"))
    with _FILE_JSON_LOCK:
        _FILE_JSON_CACHE[key] = (sig, payload)
    return payload


def load_assist_fill_instruction(path: Path | None = None) -> str:
    fill_path = Path(path) if path else ASSIST_FILL_PATH
    try:
        payload = _cached_json(fill_path)
    except (OSError, json.JSONDecodeError) as exc:
        raise PromptComposeError(f"assist fill instruction missing or invalid: {exc}") from exc
    if payload.get("schema") != SCHEMA_ASSIST_FILL:
        raise PromptComposeError(f"assist fill schema must be {SCHEMA_ASSIST_FILL}")
    text = str(payload.get("instruction") or "").strip()
    if not text:
        raise PromptComposeError("assist fill instruction is empty")
    return text


def load_policy(path: Path | None = None) -> dict[str, Any]:
    policy_path = Path(path) if path else POLICY_PATH
    try:
        payload = _cached_json(policy_path)
    except FileNotFoundError as exc:
        raise PromptComposeError(f"render policy missing: {policy_path}") from exc
    except json.JSONDecodeError as exc:
        raise PromptComposeError(f"render policy invalid JSON: {exc}") from exc
    if payload.get("schema") != SCHEMA_POLICY:
        raise PromptComposeError(f"render policy schema must be {SCHEMA_POLICY}")
    return payload


def load_pack(pack_id: str | None, *, directory: Path | None = None) -> dict[str, Any] | None:
    if not pack_id:
        return None
    path = (directory or PACK_DIR) / f"{pack_id}.pack.json"
    if not path.is_file():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def has_cjk(text: str) -> bool:
    return bool(_CJK.search(text or ""))


def strip_weight(raw: str) -> str:
    text = (raw or "").strip()
    text = text.replace("::", "")
    match = _WEIGHT.match(text)
    if match:
        text = match.group(1)
    return text.replace("{{", "").replace("}}", "").strip()


def split_tokens(text: str) -> list[str]:
    out: list[str] = []
    for part in (text or "").split(","):
        token = strip_weight(part)
        if token:
            out.append(token)
    return out


_LATIN = re.compile(r"[A-Za-z]")


def keep_unknown_as_nl(token: str) -> bool:
    """Multi-word Latin phrases stay nl_spans. Single unknown tags still drop."""
    text = (token or "").strip()
    if " " not in text or has_cjk(text):
        return False
    return bool(_LATIN.search(text))


def _policy_set(policy: dict[str, Any], key: str) -> set[str]:
    return {normalize(item) for item in (policy.get(key) or []) if item}


def _age_forbid(policy: dict[str, Any]) -> set[str]:
    return _policy_set(policy, "age_inject_forbid")


def _quality_forbid(policy: dict[str, Any]) -> set[str]:
    return _policy_set(policy, "anima_quality_forbid")


def infer_facet(norm: str, *, source: str, category: int | None, policy: dict[str, Any]) -> str:
    costume_adds = {
        normalize(item)
        for item in ((policy.get("costume") or {}).get("expose-in-costume") or {}).get("add") or []
    }
    if source == "costume" or (source == "band" and norm in costume_adds):
        return "exposure"
    if source == "leaf":
        return "fetish"
    if source == "pack" or source == "trigger":
        return "identity"
    if category == 1:
        return "artist"
    if category in {3, 4}:
        return "identity"
    pattern = policy.get("count_tag_pattern") or _COUNT.pattern
    if re.match(pattern, norm):
        return "count"
    hints = policy.get("facet_hints") or {}
    hinted = hints.get(norm) or hints.get(to_prompt(norm))
    if hinted in FACETS:
        return hinted
    suffixes = sorted(
        ((str(suffix), facet) for suffix, facet in (policy.get("facet_suffixes") or {}).items()),
        key=lambda item: len(item[0]),
        reverse=True,
    )
    for suffix, facet in suffixes:
        if suffix and norm.endswith(suffix) and facet in FACETS:
            return facet
    return "other"


def anima_surface(norm: str, category: int | None) -> str:
    """Anima three rules: spaces; @ on artist; no _ on artist/character/copyright."""
    text = to_prompt(norm)
    if category == 1 and not text.startswith("@"):
        text = "@" + text
    return text


def sdxl_surface(norm: str) -> str:
    return to_prompt(norm)


def empty_ir(*, domain: str | None = None, rating: str | None = None) -> dict[str, Any]:
    return {
        "schema": SCHEMA_IR,
        "id": None,
        "rating": rating,
        "prompt_domain": domain,
        "pack_id": None,
        "style_id": None,
        "triggers": [],
        "neg_guards": [],
        "nl_spans": [],
        "tags": [],
        "dropped_tags": [],
        "rewrites": [],
    }


def _rewrite(src: str, dst: str, kind: str) -> dict[str, str]:
    return {"from": src, "to": dst, "kind": kind}


_GATE_SPLIT = re.compile(r",|\.(?:\s+|$)")


def _gate_blob(text: str) -> str:
    return f" {normalize(text.replace(',', ' '))} "


def gate_hit(text: str, token: str) -> bool:
    needle = normalize(token)
    if not needle:
        return False
    if f" {needle} " in _gate_blob(text):
        return True
    return any(normalize(part) == needle for part in _GATE_SPLIT.split(text or ""))


def _add_tag(
    tags: list[dict[str, Any]],
    seen: set[str],
    *,
    norm: str,
    facet: str,
    source: str,
    category: int | None,
    surface: str | None = None,
) -> bool:
    if not norm or norm in seen:
        return False
    if facet not in FACETS:
        facet = "other"
    seen.add(norm)
    tags.append({
        "id": norm,
        "surface": surface or sdxl_surface(norm),
        "facet": facet,
        "source": source,
        "category": category,
    })
    return True


def resolve(
    spec: dict[str, Any] | None = None,
    *,
    tagdb: TagDB | None = None,
    policy: dict[str, Any] | None = None,
    pack: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Resolve tokens + pack + constraints into ``loramake.prompt-ir/v1``."""
    spec = dict(spec or {})
    spec["tokens"] = list(spec.get("tokens") or [])
    policy = policy or load_policy()
    domain = spec.get("domain") or spec.get("prompt_domain") or "sdxl_illustrious"
    ir = empty_ir(domain=domain, rating=spec.get("rating"))
    ir["pack_id"] = spec.get("pack_id")
    ir["style_id"] = spec.get("style_id")
    ir["triggers"] = [str(item) for item in (spec.get("triggers") or []) if item]
    dropped: list[str] = []
    rewrites: list[dict[str, str]] = []
    tags: list[dict[str, Any]] = []
    seen: set[str] = set()
    age_forbid = _age_forbid(policy)
    quality_forbid = _quality_forbid(policy)
    anima_domain = domain in ANIMA_MIXED or domain in NL_DOMAINS  # quality-tag drop applies to every NL surface

    loaded_pack = pack if pack is not None else load_pack(spec.get("pack_id"))
    identity = loaded_pack.get("prompt_identity") if isinstance(loaded_pack, dict) else None
    if isinstance(identity, dict) and not spec.get("identity_tags"):
        ir["neg_guards"] = [str(item) for item in (identity.get("neg_guards") or []) if item]
        trigger = (loaded_pack or {}).get("trigger")
        if trigger and trigger not in ir["triggers"]:
            ir["triggers"].append(str(trigger))
        for raw in list(identity.get("identity_tags") or []) + list(identity.get("color_lock") or []):
            if normalize(str(raw)) in age_forbid:
                dropped.append(str(raw))
                rewrites.append(_rewrite(str(raw), "", "age_filter"))
                continue
            spec.setdefault("tokens", []).append({"raw": raw, "facet": "identity", "source": "pack"})
    for raw in spec.get("identity_tags") or []:
        spec.setdefault("tokens", []).append({"raw": raw, "facet": "identity", "source": "user"})

    forbid = {normalize(item) for item in (spec.get("forbid") or []) if item}
    for rule in policy.get("conflicts") or []:
        when = {normalize(item) for item in (rule.get("when") or [])}
        incoming = {normalize(str(item.get("raw") or item.get("id") or "")) for item in (spec.get("tokens") or [])}
        incoming |= {normalize(item) for item in (spec.get("add") or [])}
        if when and when <= incoming:
            forbid |= {normalize(item) for item in (rule.get("drop") or [])}

    costume_policy = (spec.get("nsfw") or {}).get("costume_policy") or spec.get("costume_policy")
    costume = ((policy.get("costume") or {}).get(costume_policy) or {}) if costume_policy else {}
    for raw in costume.get("never_add") or []:
        forbid.add(normalize(raw))
    extra_add = list(spec.get("add") or [])
    extra_add.extend(costume.get("add") or [])

    raw_tokens: list[dict[str, Any]] = []
    for item in spec.get("tokens") or []:
        if isinstance(item, str):
            raw_tokens.append({"raw": item, "facet": None, "source": "user"})
        elif isinstance(item, dict):
            raw_tokens.append(item)
    for item in spec.get("leaf_tags") or []:
        if isinstance(item, str):
            raw_tokens.append({"raw": item, "facet": "fetish", "source": "leaf"})
        elif isinstance(item, dict):
            raw_tokens.append({**item, "source": item.get("source") or "leaf", "facet": item.get("facet") or "fetish"})
    for raw in extra_add:
        raw_tokens.append({
            "raw": raw,
            "facet": "exposure",
            "source": "costume" if costume_policy else "band",
        })

    def accept(raw: str, *, facet: str | None, source: str) -> None:
        token = strip_weight(raw)
        if not token:
            return
        if token.lower().startswith("flag:"):
            dropped.append(token)
            rewrites.append(_rewrite(token, "", "flag"))
            return
        if has_cjk(token) and domain in SDXL_DOMAINS:
            dropped.append(token)
            rewrites.append(_rewrite(token, "", "cjk"))
            return
        norm = normalize(token)
        if norm in age_forbid and source not in {"user", "author"}:
            dropped.append(token)
            rewrites.append(_rewrite(token, "", "age_filter"))
            return
        if anima_domain and norm in quality_forbid:
            dropped.append(token)
            rewrites.append(_rewrite(token, "", "anima_quality"))
            return
        if norm in forbid:
            dropped.append(token)
            rewrites.append(_rewrite(token, "", "forbid"))
            return
        hit = norm
        category = None
        hops: list[dict[str, str]] = []
        if tagdb is not None:
            resolved, hops = tagdb.resolve(token)
            if resolved is None:
                if keep_unknown_as_nl(token):
                    ir["nl_spans"].append({
                        "text": token,
                        "facet": "face" if "face" in normalize(token) else "other",
                        "from_ids": [],
                        "source": source,
                    })
                    rewrites.append(_rewrite(token, token, "nl_keep"))
                    return
                dropped.append(token)
                return
            hit = resolved
            row = tagdb.row_for(hit)
            category = row.category if row else None
            rewrites.extend(hops)
            if hit in forbid:
                dropped.append(token)
                rewrites.append(_rewrite(hit, "", "forbid"))
                return
            if anima_domain and hit in quality_forbid:
                dropped.append(token)
                rewrites.append(_rewrite(hit, "", "anima_quality"))
                return
        facet_name = facet if facet in FACETS else infer_facet(hit, source=source, category=category, policy=policy)
        if anima_domain:
            surface = anima_surface(hit, category)
        else:
            surface = sdxl_surface(hit)
        _add_tag(tags, seen, norm=hit, facet=facet_name, source=source, category=category, surface=surface)

    for item in raw_tokens:
        accept(str(item.get("raw") or item.get("id") or ""), facet=item.get("facet"), source=str(item.get("source") or "user"))

    if tagdb is not None:
        for tag in list(tags):
            for consequent in tagdb.implied(tag["id"]):
                if consequent in seen or consequent in forbid:
                    continue
                if anima_domain and consequent in quality_forbid:
                    continue
                row = tagdb.row_for(consequent)
                category = row.category if row else None
                facet_name = infer_facet(consequent, source="implication", category=category, policy=policy)
                surface = anima_surface(consequent, category) if anima_domain else sdxl_surface(consequent)
                if _add_tag(
                    tags, seen, norm=consequent, facet=facet_name, source="implication",
                    category=category, surface=surface,
                ):
                    rewrites.append(_rewrite(tag["id"], consequent, "implication"))

    for group in spec.get("require_any_groups") or []:
        options = [normalize(item) for item in group if item]
        if options and not any(item in seen for item in options):
            accept(group[0], facet="exposure", source="band")

    order = {name: index for index, name in enumerate(policy.get("facet_order") or FACETS)}
    tags.sort(key=lambda tag: (order.get(tag["facet"], 99), tag.get("category") if tag.get("category") is not None else 4, tag["id"]))

    ir["tags"] = tags
    ir["dropped_tags"] = dropped
    ir["rewrites"] = rewrites
    nsfw = spec.get("nsfw")
    if isinstance(nsfw, dict) and nsfw:
        overlay = dict(nsfw)
        overlay.setdefault("schema", "nsfw.prompt-ir/v1")
        ir["nsfw"] = overlay
    for hint in spec.get("nl_hints") or []:
        text = str(hint).strip()
        if not text:
            continue
        if domain in SDXL_DOMAINS:
            continue
        ir["nl_spans"].append({"text": text, "facet": "light", "from_ids": [], "source": "hint"})
    return ir


def _tags_for_facets(ir: dict[str, Any], facets: Iterable[str]) -> list[dict[str, Any]]:
    wanted = set(facets)
    return [tag for tag in ir.get("tags") or [] if tag.get("facet") in wanted]


def _join_surfaces(tags: Iterable[dict[str, Any]], *, join: str = ", ", spaces: bool = False) -> str:
    """Join tag surfaces. ``join="and"`` writes a natural list ("a, b and c"); ``spaces`` turns
    ``silver_hair`` into ``silver hair`` for sentence surfaces."""
    seen: set[str] = set()
    out: list[str] = []
    for tag in tags:
        surface = str(tag.get("surface") or sdxl_surface(str(tag.get("id") or ""))).strip()
        if spaces:
            surface = surface.replace("_", " ")
        key = surface.lower()
        if not surface or key in seen:
            continue
        seen.add(key)
        out.append(surface)
    if join == "and":
        if len(out) <= 1:
            return "".join(out)
        return ", ".join(out[:-1]) + " and " + out[-1]
    return join.join(out)


def _nl_policy_key(domain: str) -> str:
    return "qwen21_nl" if domain in QWEN_NL else "anima_nl"


def _append_triggers(parts: list[str], ir: dict[str, Any]) -> None:
    blob = " ".join(parts).lower()
    for trigger in ir.get("triggers") or []:
        token = str(trigger).strip()
        if token and token.lower() not in blob:
            parts.insert(0, token)


def render(
    ir: dict[str, Any],
    domain: str | None = None,
    *,
    policy: dict[str, Any] | None = None,
) -> RenderResult:
    """Render one IR onto an SDXL or Anima surface. Same IR, two renderers."""
    if ir.get("schema") != SCHEMA_IR:
        raise PromptComposeError(f"IR schema must be {SCHEMA_IR}")
    policy = policy or load_policy()
    domain = domain or ir.get("prompt_domain") or "sdxl_illustrious"
    recoverability: list[dict[str, Any]] = []
    mixed = policy.get("anima_mixed") or {}
    nl_cfg = policy.get(_nl_policy_key(domain)) or {}

    if domain in SDXL_DOMAINS or domain not in ANIMA_MIXED | NL_DOMAINS:
        parts = [_join_surfaces(ir.get("tags") or [])]
        for span in ir.get("nl_spans") or []:
            text = str(span.get("text") or "").strip()
            if text:
                parts.append(text)
        _append_triggers(parts, ir)
        prompt = ", ".join(part for part in parts if part)
        return RenderResult(
            prompt=prompt,
            domain=domain,
            ir=ir,
            dropped_tags=tuple(ir.get("dropped_tags") or ()),
            rewrites=tuple(ir.get("rewrites") or ()),
        )

    if domain in ANIMA_MIXED:
        hard = _join_surfaces(_tags_for_facets(ir, mixed.get("tag_facets") or []))
        nl_bits: list[str] = []
        for span in ir.get("nl_spans") or []:
            text = str(span.get("text") or "").strip()
            if text:
                nl_bits.append(text)
                recoverability.append({"text": text, "from_ids": list(span.get("from_ids") or []), "facet": span.get("facet")})
        for tag in _tags_for_facets(ir, mixed.get("nl_facets") or []):
            nl_bits.append(str(tag.get("surface") or tag["id"]))
            recoverability.append({"text": tag.get("surface"), "from_ids": [tag["id"]], "facet": tag.get("facet")})
        if not _tags_for_facets(ir, ("light", "scene")):
            mood = str(mixed.get("default_mood") or "").strip()
            if mood and mood not in nl_bits:
                nl_bits.append(mood)
                recoverability.append({"text": mood, "from_ids": [], "facet": "light"})
        hard_parts = [hard]
        _append_triggers(hard_parts, ir)
        hard = ", ".join(part for part in hard_parts if part)
        if hard and nl_bits:
            prompt = f"{hard}. {' '.join(nl_bits)}"
        else:
            prompt = hard or " ".join(nl_bits)
        return RenderResult(
            prompt=prompt,
            domain=domain,
            ir=ir,
            dropped_tags=tuple(ir.get("dropped_tags") or ()),
            rewrites=tuple(ir.get("rewrites") or ()),
            recoverability=recoverability,
        )

    # anima_nl / flux_nl / qwen21_nl — verbalize from IR, no age flatten
    sentences: list[str] = []
    raw_keep: list[str] = []
    keep_sources = set(nl_cfg.get("keep_raw_sources") or ())
    keep_artist_raw = bool(nl_cfg.get("keep_artist_raw", True))
    surface_spaces = bool(nl_cfg.get("surface_spaces", False))
    for tag in ir.get("tags") or []:
        if tag.get("source") in keep_sources or (keep_artist_raw and tag.get("facet") == "artist"):
            raw_keep.append(str(tag.get("surface") or tag["id"]))
    for trigger in ir.get("triggers") or []:
        if str(trigger) not in raw_keep:
            raw_keep.append(str(trigger))
    for part in nl_cfg.get("parts") or []:
        surfaces = _join_surfaces(
            _tags_for_facets(ir, part.get("from_facets") or []),
            join=str(part.get("join") or ", "),
            spaces=surface_spaces,
        )
        if not surfaces:
            continue
        template = part.get("template")
        if template:
            sentence = str(template).format(surfaces=surfaces).strip()
        else:
            prefix = str(part.get("prefix") or "")
            sentence = f"{prefix}{surfaces}".strip()
        sentences.append(sentence)
        recoverability.append({
            "text": sentence,
            "from_ids": [tag["id"] for tag in _tags_for_facets(ir, part.get("from_facets") or [])],
            "facet": (part.get("from_facets") or ["other"])[0],
        })
    for span in ir.get("nl_spans") or []:
        text = str(span.get("text") or "").strip()
        if text:
            sentences.append(text)
            recoverability.append({"text": text, "from_ids": list(span.get("from_ids") or []), "facet": span.get("facet")})
    body = " ".join(sentences).strip()
    if raw_keep:
        head = ", ".join(dict.fromkeys(raw_keep))
        prompt = f"{head}. {body}".strip() if body else head
    else:
        prompt = body
    return RenderResult(
        prompt=prompt,
        domain=domain,
        ir=ir,
        dropped_tags=tuple(ir.get("dropped_tags") or ()),
        rewrites=tuple(ir.get("rewrites") or ()),
        recoverability=recoverability,
    )


def validate(
    ir: dict[str, Any],
    prompt: str,
    domain: str | None = None,
    *,
    tagdb: TagDB | None = None,
    policy: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Fail-closed structural checks. Callers on the agent path may treat problems as lint."""
    policy = policy or load_policy()
    domain = domain or ir.get("prompt_domain") or "sdxl_illustrious"
    problems: list[str] = []
    age_forbid = _age_forbid(policy)
    quality_forbid = _quality_forbid(policy)
    input_ids = {normalize(str(tag.get("id") or "")) for tag in ir.get("tags") or []}
    input_ids |= {normalize(str(item)) for item in ir.get("triggers") or []}

    if domain in SDXL_DOMAINS and has_cjk(prompt):
        problems.append("cjk_on_il")
    if "flag:" in (prompt or "").lower():
        problems.append("flag_token")

    for token in age_forbid:
        if gate_hit(prompt, token) and token not in input_ids:
            problems.append(f"age_inject:{token}")

    if domain in ANIMA_MIXED | NL_DOMAINS:
        for token in quality_forbid:
            if gate_hit(prompt, token):
                problems.append(f"anima_quality:{token}")
    if domain in ANIMA_MIXED | ANIMA_NL:  # Anima-only surface rules; not the Qwen line
        for tag in ir.get("tags") or []:
            category = tag.get("category")
            surface = str(tag.get("surface") or "")
            if category in {1, 3, 4} and "_" in surface.replace("@", ""):
                problems.append(f"anima_underscore:{tag.get('id')}")
            if category == 1 and not surface.startswith("@"):
                problems.append(f"anima_artist_at:{tag.get('id')}")

    if domain in SDXL_DOMAINS and tagdb is not None:
        nl_ok = {normalize(str(span.get("text") or "")) for span in ir.get("nl_spans") or []}
        for raw in split_tokens(prompt):
            if raw in (ir.get("triggers") or []):
                continue
            if normalize(raw) in nl_ok:
                continue
            hit, _hops = tagdb.resolve(raw)
            if hit is None:
                problems.append(f"unknown_tag:{raw}")

    return {
        "ok": not problems,
        "problems": problems,
        "dropped_tags": list(ir.get("dropped_tags") or []),
        "rewrites": list(ir.get("rewrites") or []),
        "prompt_domain": domain,
    }


def resolve_from_leaf_tags(
    primary: Iterable[str],
    support: Iterable[str] | None = None,
    *,
    domain: str = "sdxl_illustrious",
    subintent: str | None = None,
    include_support: bool = True,
    tagdb: TagDB | None = None,
    policy: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """Adapter used by nsfw/l2_render. No age flatten."""
    policy = policy or load_policy()
    tokens = [{"raw": item, "facet": "fetish", "source": "leaf"} for item in primary or []]
    if include_support:
        tokens.extend({"raw": item, "facet": "action", "source": "leaf"} for item in (support or []))
    hints: list[str] = []
    if domain in ANIMA_MIXED and subintent:
        hints.append(str((policy.get("anima_mixed") or {}).get("subintent_template") or "Emphasis on {subintent}.").format(subintent=subintent.replace("_", " ")))
    return resolve({"tokens": tokens, "domain": domain, "nl_hints": hints}, tagdb=tagdb, policy=policy)


def render_from_leaf_tags(
    domain: str,
    primary: Iterable[str],
    support: Iterable[str] | None = None,
    *,
    subintent: str | None = None,
    include_support: bool = True,
    tagdb: TagDB | None = None,
    policy: dict[str, Any] | None = None,
) -> str:
    ir = resolve_from_leaf_tags(
        primary, support, domain=domain, subintent=subintent,
        include_support=include_support, tagdb=tagdb, policy=policy,
    )
    return render(ir, domain, policy=policy).prompt


def domain_for_intent(intent: str | None) -> str:
    if intent in ANIMA_INTENTS:
        return "anima_mixed"
    if intent in QWEN21_INTENTS:
        return "qwen21_nl"
    return "sdxl_illustrious"


def compact_ir(ir: dict[str, Any] | None) -> dict[str, Any] | None:
    if not isinstance(ir, dict) or ir.get("schema") != SCHEMA_IR:
        return None
    tags = ir.get("tags")
    tag_ids = [
        tag.get("id")
        for tag in tags
        if isinstance(tag, dict) and tag.get("id")
    ][:48] if isinstance(tags, list) else []
    dropped = ir.get("dropped_tags")
    return {
        "schema": ir.get("schema"),
        "id": ir.get("id"),
        "prompt_domain": ir.get("prompt_domain"),
        "pack_id": ir.get("pack_id"),
        "rating": ir.get("rating"),
        "tag_ids": tag_ids,
        "dropped_tags": list(dropped)[:24] if isinstance(dropped, list) else [],
    }


def parse_slot_proposal(raw: str | None) -> dict[str, Any] | None:
    """Parse optional LLM slot JSON or a comma tag line. Never treats the line as final prompt."""
    text = (raw or "").strip()
    if not text:
        return None
    if text.startswith("```"):
        lines = text.splitlines()
        if lines and lines[0].startswith("```"):
            lines = lines[1:]
        if lines and lines[-1].strip() == "```":
            lines = lines[:-1]
        text = "\n".join(lines).strip()
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return {"tokens": split_tokens(text)}
    if not isinstance(data, dict):
        return {"tokens": split_tokens(text)}
    tokens = data.get("tokens") or data.get("tags") or []
    if isinstance(tokens, str):
        tokens = split_tokens(tokens)
    elif not isinstance(tokens, list):
        tokens = []
    slots = dict(data["slots"]) if isinstance(data.get("slots"), dict) else {}
    for key in ("leaf_ids", "exposure_band", "behavior_band"):
        if key in data and key not in slots:
            slots[key] = data[key]
    return {
        "tokens": [str(item) for item in tokens if item],
        "pack_id": data.get("pack_id"),
        "style_id": data.get("style_id"),
        "prompt_domain": data.get("prompt_domain") or data.get("domain"),
        "slots": slots or None,
    }


def _optional_tagdb(directory: Path | None = None) -> TagDB | None:
    """None only when no extract is installed. Corrupt/stale TagDBError propagates."""
    from loramake.tags import load_tagdb, load_tagdb_if_present

    try:
        if directory:
            return load_tagdb(directory)
        return load_tagdb_if_present()
    except TagDBError:
        raise
    except Exception:
        return None


def _domain_from_nsfw_profile(profile: str | None, slots: dict[str, Any] | None = None) -> str:
    slots = slots or {}
    if profile:
        try:
            from nsfw.nsfw_compose import defaults

            prof = (defaults().get("profiles") or {}).get(profile) or {}
            if prof.get("prompt_domain"):
                return str(prof["prompt_domain"])
        except Exception:
            pass
    line = str((slots.get("base") or {}).get("line") or "")
    try:
        from nsfw.nsfw_compose import defaults

        mapped = (defaults().get("line_to_prompt_domain") or {}).get(line)
        if mapped:
            return str(mapped)
    except Exception:
        pass
    return "sdxl_illustrious"


def _loras_from_slots(slots: dict[str, Any] | None) -> list[str]:
    out: list[str] = []
    if not isinstance(slots, dict):
        return out
    ident = slots.get("identity") or {}
    if isinstance(ident, dict) and ident.get("lora_file"):
        out.append(str(ident["lora_file"]))
    style = slots.get("style") or {}
    if isinstance(style, dict) and style.get("lora_file"):
        out.append(str(style["lora_file"]))
    return out


def _nsfw_fill(
    text: str,
    *,
    domain: str | None,
    profile: str | None,
    slots_in: dict[str, Any] | None,
    proposal: dict[str, Any] | None,
    tagdb: TagDB | None,
    policy: dict[str, Any],
) -> dict[str, Any]:
    try:
        from nsfw.nsfw_compose import fill_slots
        from nsfw.prompt_ir import compose_prompt_from_slots
    except ImportError as exc:
        raise PromptComposeError(f"nsfw compose unavailable: {exc}") from exc

    merged = dict(slots_in or {})
    if proposal:
        extra = proposal.get("slots") if isinstance(proposal.get("slots"), dict) else None
        if extra:
            for key, value in extra.items():
                if key in {"schema", "schema_version", "tokens", "tags", "prompt"}:
                    continue
                merged[key] = value
        tokens = proposal.get("tokens") or []
        if tokens:
            merged["prompt_override"] = ", ".join(str(item) for item in tokens)
    slots = fill_slots(text, slots_in=merged or None, profile=profile)
    domain = domain or _domain_from_nsfw_profile(profile, slots)
    packed = compose_prompt_from_slots(slots, domain, tagdb=tagdb)
    return {
        "slots": slots,
        "ir": packed["ir"],
        "prompt": packed["prompt"],
        "prompt_domain": domain,
        "dropped_tags": list(packed.get("dropped_tags") or []),
        "rewrites": list(packed.get("rewrites") or []),
        "lint": packed.get("lint") or {"ok": True, "problems": []},
        "loras_suggested": _loras_from_slots(slots),
        "policy": policy,
    }


def fill(
    text: str,
    *,
    nsfw: bool = False,
    domain: str | None = None,
    profile: str | None = None,
    pack_id: str | None = None,
    slots_in: dict[str, Any] | None = None,
    proposal: dict[str, Any] | None = None,
    tagdb: TagDB | None = None,
    policy: dict[str, Any] | None = None,
) -> dict[str, Any]:
    """NL and/or slot JSON → IR + domain prompt. Agents do not author the final string."""
    policy = policy or load_policy()
    text = (text or "").strip()
    slots_in = dict(slots_in or {})
    if nsfw:
        return _nsfw_fill(
            text, domain=domain, profile=profile, slots_in=slots_in,
            proposal=proposal, tagdb=tagdb, policy=policy,
        )
    domain = (
        domain
        or (proposal or {}).get("prompt_domain")
        or slots_in.get("prompt_domain")
        or "sdxl_illustrious"
    )
    pack_id = pack_id or (proposal or {}).get("pack_id") or slots_in.get("pack_id")
    tokens: list[Any] = []
    if text:
        tokens.extend(split_tokens(text))
    for raw in slots_in.get("tokens") or []:
        tokens.append(raw)
    if proposal:
        tokens.extend(proposal.get("tokens") or [])
    spec_tokens = [
        item if isinstance(item, dict) else {"raw": item, "source": "user"}
        for item in tokens
        if item
    ]
    spec = {
        "tokens": spec_tokens,
        "domain": domain,
        "pack_id": pack_id,
        "style_id": slots_in.get("style_id") or (proposal or {}).get("style_id"),
    }
    ir = resolve(spec, tagdb=tagdb, policy=policy)
    result = render(ir, domain, policy=policy)
    lint = validate(ir, result.prompt, domain, tagdb=tagdb, policy=policy)
    slots = {
        "schema_version": SCHEMA_FILL_SLOTS,
        "raw_request": text,
        "tokens": [item["raw"] if isinstance(item, dict) else item for item in spec_tokens],
        "pack_id": pack_id,
        "style_id": spec.get("style_id"),
        "prompt_domain": domain,
    }
    return {
        "slots": slots,
        "ir": ir,
        "prompt": result.prompt,
        "prompt_domain": domain,
        "dropped_tags": list(ir.get("dropped_tags") or []),
        "rewrites": list(ir.get("rewrites") or []),
        "lint": lint,
        "loras_suggested": [],
    }


def _has_structured_slots(slots: dict[str, Any] | None, proposal: dict[str, Any] | None) -> bool:
    for blob in (slots, proposal):
        if not isinstance(blob, dict):
            continue
        if blob.get("tokens") or blob.get("leaf_ids"):
            return True
        identity = blob.get("identity")
        if isinstance(identity, dict) and any(identity.values()):
            return True
    return False


def _looks_like_comma_tags(text: str) -> bool:
    return "," in (text or "") and bool(split_tokens(text))


def assist_compose(
    text: str,
    *,
    nsfw: bool = False,
    domain: str | None = None,
    profile: str | None = None,
    pack_id: str | None = None,
    slots: dict[str, Any] | None = None,
    llm_text: str | None = None,
    tagdb: TagDB | None = None,
) -> dict[str, Any]:
    """fill + compose + validate. HTTP/CLI contract for /api/assist."""
    if tagdb is None:
        tagdb = _optional_tagdb()
    proposal = parse_slot_proposal(llm_text)
    filled = fill(
        text,
        nsfw=nsfw,
        domain=domain,
        profile=profile,
        pack_id=pack_id,
        slots_in=slots,
        proposal=proposal,
        tagdb=tagdb,
    )
    warnings: list[str] = []
    lint = filled.get("lint") or {}
    prompt = (filled.get("prompt") or "").strip()
    if not prompt:
        structured = _has_structured_slots(slots, proposal) or _looks_like_comma_tags(text)
        if not structured:
            raise PromptComposeError(
                "compose produced empty prompt; no structured slots or comma tags"
            )
        warnings.append("compose produced empty prompt; kept original brief (lint/warn)")
        filled["prompt"] = text
        lint = validate(
            filled["ir"],
            text,
            filled.get("prompt_domain"),
            tagdb=tagdb,
        )
        filled["lint"] = lint
        filled["dropped_tags"] = list(lint.get("dropped_tags") or filled.get("dropped_tags") or [])
    if lint.get("problems"):
        warnings.append(f"validate lint: {lint.get('problems')}")
    return {
        "ir": filled["ir"],
        "prompt": filled["prompt"],
        "prompt_domain": filled["prompt_domain"],
        "dropped_tags": filled["dropped_tags"],
        "rewrites": filled["rewrites"],
        "loras_suggested": filled["loras_suggested"],
        "tagdb_ready": tagdb is not None,
        "lint": lint,
        "slots": filled["slots"],
        "warnings": warnings,
    }


def apply_optional_ir(
    *,
    ir: dict[str, Any] | str | Path | None,
    prompt: str | None,
    intent: str | None = None,
    domain: str | None = None,
    require: bool | None = None,
) -> dict[str, Any]:
    """Optional --ir for gen.py / gen_nsfw.py. Missing IR is lint/warn, never an exit."""
    warnings: list[str] = []
    if require is None:
        require = os.environ.get(REQUIRE_IR_ENV, "") == "1"
    if intent in NO_IR_INTENTS:
        if ir:
            warnings.append(f"intent {intent} does not consume --ir this release")
        return {"prompt": prompt, "ir": None, "warnings": warnings, "lint": None, "rendered": None}
    loaded: dict[str, Any] | None = None
    if isinstance(ir, dict):
        loaded = ir
    elif ir:
        try:
            loaded = _load_json_arg(str(ir))
        except (OSError, json.JSONDecodeError) as exc:
            warnings.append(f"ir unreadable ({exc}); lint/warn this release")
            if require:
                warnings.append(f"{REQUIRE_IR_ENV}=1 is not fail-closed this release")
            return {"prompt": prompt, "ir": None, "warnings": warnings, "lint": None, "rendered": None}
    if not loaded:
        warnings.append(IR_MISSING_WARN)
        if require:
            warnings.append(f"{REQUIRE_IR_ENV}=1 is not fail-closed this release")
        return {"prompt": prompt, "ir": None, "warnings": warnings, "lint": None, "rendered": None}
    domain = domain or loaded.get("prompt_domain") or domain_for_intent(intent)
    policy = load_policy()
    try:
        result = render(loaded, domain, policy=policy)
        lint = validate(loaded, result.prompt, domain, policy=policy)
    except PromptComposeError as exc:
        warnings.append(f"ir render lint: {exc}; kept --prompt (lint/warn this release)")
        return {"prompt": prompt, "ir": loaded, "warnings": warnings, "lint": None, "rendered": None}
    if lint.get("problems"):
        warnings.append(f"ir validate lint: {lint.get('problems')}")
    existing = (prompt or "").strip()
    if existing and existing != result.prompt:
        warnings.append("--prompt overrides rendered IR (lint/warn this release)")
    return {
        "prompt": existing or result.prompt,
        "ir": loaded,
        "warnings": warnings,
        "lint": lint,
        "rendered": result.prompt,
        "dropped_tags": list(loaded.get("dropped_tags") or []),
        "rewrites": list(loaded.get("rewrites") or []),
    }


def emit_ir_warnings(warnings: Iterable[str], *, stream=None) -> None:
    out = stream or sys.stderr
    for item in warnings:
        print(f"[ir] {item}", file=out)


def _print(payload: Any) -> None:
    print(json.dumps(payload, ensure_ascii=False, indent=2))


def _load_json_arg(raw: str | None) -> dict[str, Any]:
    if not raw:
        return {}
    path = Path(raw)
    if path.is_file():
        return json.loads(path.read_text(encoding="utf-8"))
    return json.loads(raw)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)

    fill_p = sub.add_parser("fill", help="NL or slots → IR + prompt (PLAN; no GPU)")
    fill_p.add_argument("text", nargs="?", default="", help="natural-language brief")
    fill_p.add_argument("--text", dest="text_opt", help="brief (wins over positional)")
    fill_p.add_argument("--nsfw", action="store_true")
    fill_p.add_argument("--profile", help="nsfw compose profile (il_boxb / anima_harem)")
    fill_p.add_argument("--domain")
    fill_p.add_argument("--pack")
    fill_p.add_argument("--slots", help="partial slots JSON or path")
    fill_p.add_argument("--dir", type=Path, help="optional TagDB extract dir")

    resolve_p = sub.add_parser("resolve", help="print IR JSON (PLAN; no GPU)")
    resolve_p.add_argument("--spec", help="resolve spec JSON or path")
    resolve_p.add_argument("--tags", help="comma-separated author tags")
    resolve_p.add_argument("--domain", default="sdxl_illustrious")
    resolve_p.add_argument("--pack")
    resolve_p.add_argument("--dir", type=Path, help="optional TagDB extract dir")

    render_p = sub.add_parser("render", help="render an IR (PLAN; no GPU)")
    render_p.add_argument("--ir", required=True)
    render_p.add_argument("--domain")

    validate_p = sub.add_parser("validate", help="fail-closed IR + prompt checks")
    validate_p.add_argument("--ir", required=True)
    validate_p.add_argument("--prompt", required=True)
    validate_p.add_argument("--domain")
    validate_p.add_argument("--dir", type=Path)

    args = parser.parse_args(argv)
    try:
        policy = load_policy()
        if args.command == "fill":
            brief = (args.text_opt or args.text or "").strip()
            if not brief and not args.slots:
                raise PromptComposeError("fill needs a brief or --slots")
            tagdb = _optional_tagdb(args.dir)
            filled = fill(
                brief,
                nsfw=bool(args.nsfw),
                domain=args.domain,
                profile=args.profile,
                pack_id=args.pack,
                slots_in=_load_json_arg(args.slots) if args.slots else None,
                tagdb=tagdb,
                policy=policy,
            )
            _print({
                "schema": SCHEMA_PLAN,
                "mode": "PLAN",
                "ir": filled["ir"],
                "prompt": filled["prompt"],
                "prompt_domain": filled["prompt_domain"],
                "dropped_tags": filled["dropped_tags"],
                "rewrites": filled["rewrites"],
                "loras_suggested": filled["loras_suggested"],
                "lint": filled["lint"],
                "slots": filled["slots"],
            })
            return EXIT_OK
        if args.command == "resolve":
            spec = _load_json_arg(args.spec)
            if args.tags:
                spec.setdefault("tokens", [])
                spec["tokens"].extend({"raw": item, "source": "user"} for item in split_tokens(args.tags))
            spec["domain"] = args.domain or spec.get("domain")
            if args.pack:
                spec["pack_id"] = args.pack
            tagdb = None
            if args.dir:
                from loramake.tags import load_tagdb

                tagdb = load_tagdb(args.dir)
            ir = resolve(spec, tagdb=tagdb, policy=policy)
            _print({"schema": SCHEMA_PLAN, "mode": "PLAN", "ir": ir})
            return EXIT_OK
        ir = _load_json_arg(args.ir)
        if args.command == "render":
            result = render(ir, args.domain, policy=policy)
            _print({"schema": SCHEMA_PLAN, "mode": "PLAN", **result.to_json()})
            return EXIT_OK
        tagdb = None
        if args.dir:
            from loramake.tags import load_tagdb

            tagdb = load_tagdb(args.dir)
        report = validate(ir, args.prompt, args.domain, tagdb=tagdb, policy=policy)
        _print(report)
        return EXIT_OK if report["ok"] else EXIT_INVALID
    except (PromptComposeError, TagDBError, OSError, json.JSONDecodeError) as exc:
        _print({"error": str(exc), "dropped_tags": []})
        return EXIT_INVALID


if __name__ == "__main__":
    raise SystemExit(main())
